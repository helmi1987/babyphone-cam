export const LANGS = ['de', 'en', 'it', 'fr'];
// Native names for the language choice (not translated).
export const LANG_NAMES = { de: 'Deutsch', en: 'English', it: 'Italiano', fr: 'Français' };

// Browser language: first supported entry of navigator.languages; Swiss German counts as German; else English.
export function browserLang(prefs) {
  const list = prefs || (navigator.languages?.length ? navigator.languages : [navigator.language || '']);
  for (const p of list) {
    const base = String(p || '').toLowerCase().split(/[-_]/)[0];
    if (base === 'gsw') return 'de';
    if (LANGS.includes(base)) return base;
  }
  return 'en';
}

// Setting value ('auto' | de | en | it | fr) -> language code.
export function resolveLang(setting) {
  return LANGS.includes(setting) ? setting : browserLang();
}

// Current language; a live binding, so importers always see the value set by setLang().
export let lang = 'en';

export function setLang(setting) {
  lang = resolveLang(setting);
  document.documentElement.lang = lang;
  return lang;
}

setLang('auto');

export function t(key, vars) {
  let s = strings[lang][key] ?? strings.en[key] ?? strings.de[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function clock(ts) {
  try {
    return new Date(ts).toLocaleTimeString(lang, { hour: '2-digit', minute: '2-digit' });
  } catch {
    return '';
  }
}

